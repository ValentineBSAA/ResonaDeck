const fs=require('fs'),assert=require('node:assert/strict'),path=require('path');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'src/index.js'),'utf8');
const dist=fs.readFileSync(path.join(root,'dist/index.js'),'utf8');
const pack=JSON.parse(fs.readFileSync(path.join(root,'assets/idle-messages.json'),'utf8'));
assert.equal(src,dist);
assert(src.includes("const RD_VERSION = '1.0.8';"));
assert.equal(pack.messages.length,2048);
assert.equal(new Set(pack.messages).size,2048);
assert(src.includes("call('get_idle_messages')"),'editable message RPC must persist');
assert(src.includes('rdV102EmblemSpin'),'full icon rotation keyframes absent');
assert(src.includes('rdV103VinylSpin') && src.includes('rd-v103-turntable'),'record-and-logo spin must be applied');
assert(src.includes('rdV102OuterOrbit')&&src.includes('rdV102AuraBreathe'),'missing secondary animated layers');
assert(src.includes("${visible?'':'rd-v102-idle-paused'}"),'animation must pause when QAM is hidden');
