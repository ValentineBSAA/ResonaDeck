assert(src.includes("documentRoot?.classList?.add('rd-v102-pointer-hidden-qam')"),'QAM pointer suppression must reach Steam document');
assert(src.includes("documentRoot?.classList?.remove('rd-v102-pointer-hidden-qam')"),'QAM pointer must restore on mouse activity or cleanup');
