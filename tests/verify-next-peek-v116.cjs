'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const code=fs.readFileSync('src/index.js','utf8');
assert.equal(code,fs.readFileSync('dist/index.js','utf8'));
assert(code.includes("const RD_VERSION = '1.1.6'"));
const start=code.indexOf('  const nextIndex=Number(s.index||0)+1<');
const end=code.indexOf('  const secondary=music?',start);
assert(start>=0&&end>start,'Next Up overlay code present');
const snippet=code.slice(start,end);
const cx={Math,Number,String,Boolean,Infinity,rdArtPathForRoleV83:item=>String(item.thumb||'fallback'),console};
vm.createContext(cx);
vm.runInContext(`this.preview=function(s,shownDur,shownPos,surpriseOpen=false,queueOpen=false){const music=true;const cur=s.current;const discovery={preferences:{crossfade:8}};${snippet};return {showNextCover, nextIndex, nextSongArtPath};}`,cx);
const q=[{ratingKey:'a',title:'Now'},{ratingKey:'b',title:'Upcoming',thumb:'album-b'}];
const base={queue:q,index:0,repeatMode:'off',state:'playing',current:q[0]};
assert.equal(cx.preview(base,120,110).showNextCover,true,'shows 10 seconds from track end');
assert.equal(cx.preview(base,120,50).showNextCover,false,'hidden most of the song');
assert.equal(cx.preview(base,120,110,true).showNextCover,false,'hidden while settings active');
assert.equal(cx.preview(base,120,110,false,true).showNextCover,false,'hidden while queue open');
assert.equal(cx.preview({...base,index:1,current:q[1]},120,20).showNextCover,false,'disappears after handoff');
assert.equal(cx.preview({...base,index:1,current:q[1],repeatMode:'all'},120,110).showNextCover,true,'supports repeat-all wrap');
assert.equal(cx.preview({...base,state:'paused'},120,110).showNextCover,false,'hidden when paused');
assert.equal(cx.preview(base,0,0).showNextCover,false,'does not guess if track length unknown');
assert.equal(cx.preview(base,120,110).nextSongArtPath,'album-b','gets real upcoming artwork');
assert(code.includes('pointer-events:none!important;animation:rd-v116-arrive'),'preview does not steal Steam controller focus');
console.log('PASS: Up Next appears near the switch, hides while paused/settings/queue/after change, chooses queued album artwork, controller focus untouched');
